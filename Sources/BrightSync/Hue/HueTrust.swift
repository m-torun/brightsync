    static let roots: [SecCertificate] = rootsPEM
        .components(separatedBy: "-----BEGIN CERTIFICATE-----")
        .compactMap { block in
            let body = block.components(separatedBy: "-----END CERTIFICATE-----")[0]
            guard let der = Data(base64Encoded: body, options: .ignoreUnknownCharacters), !der.isEmpty else { return nil }
            return SecCertificateCreateWithData(nil, der as CFData)
        }

    /// The bridge ID the certificate names, if the chain checks out and, when
    /// one is expected, it is that bridge.
    static func bridgeID(of trust: SecTrust, expected: String?) -> String? {
        SecTrustSetPolicies(trust, SecPolicyCreateBasicX509())
        SecTrustSetAnchorCertificates(trust, roots as CFArray)
        SecTrustSetAnchorCertificatesOnly(trust, true)
        guard SecTrustEvaluateWithError(trust, nil),
              let chain = SecTrustCopyCertificateChain(trust) as? [SecCertificate],
              let leaf = chain.first else { return nil }
        var name: CFString?
        SecCertificateCopyCommonName(leaf, &name)
        guard let id = name as String? else { return nil }
        if let expected, id.lowercased() != expected.lowercased() {
            return nil
        }
        return id
    }
